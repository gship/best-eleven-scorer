class Player {
  final int index;
  final int allPlayersIndex;
  final String name;
  final Color color;
  final bool hasTheInName;
  final int points;
  final bool isKeeper;
  final bool isDefender;
  final bool isMid;
  final bool isForward;
  final int numberOfSkills;
  final int numberOfSavvies;
  final int numberOfSpeeds;
  final int numberOfStrengths;
  final List<Symbol> symbols;
  final int numberOfSymbols;
  final bool hasSigningBonus;
  final bool hasWildStat;
  final int defendersIndex;
  final int midfieldersIndex;
  final int forwardsIndex;
  final BonusStipulation? pointsScoringBonus;

  const Player(
    this.index,
    this.allPlayersIndex,
    this.name,
    this.color,
    this.hasTheInName,
    this.points,
    this.isKeeper,
    this.isDefender,
    this.isMid,
    this.isForward,
    this.numberOfSkills,
    this.numberOfSavvies,
    this.numberOfSpeeds,
    this.numberOfStrengths,
    this.symbols,
    this.numberOfSymbols,
    this.hasSigningBonus,
    this.hasWildStat,
    this.defendersIndex,
    this.midfieldersIndex,
    this.forwardsIndex,
    this.pointsScoringBonus,
  );

  int getPositionIndex(Position position) {
    switch (position) {
      case Position.defender:
        return defendersIndex;
      case Position.midfielder:
        return midfieldersIndex;
      case Position.forward:
        return forwardsIndex;
      default:
        return -1;
    }
  }

  String toValuesString() {
    return '$index)';
  }

  @override
  String toString() {
    return name;
  }

  @override
  bool operator ==(Object other) {
    if (other.runtimeType != runtimeType) {
      return false;
    }
    return other is Player && other.name == name;
  }

  @override
  int get hashCode => Object.hash(index, name);
}

