class Player {
  late int index;
  String name;
  Color color;
  bool hasTheInName = false;
  int points = 0;
  bool isKeeper = false;
  bool isDefender = false;
  bool isMid = false;
  bool isForward = false;
  int numberOfSkills = 0;
  int numberOfSavvies = 0;
  int numberOfSpeeds = 0;
  int numberOfStrengths = 0;

  //int bonusPoints = 0;
  //BonusStipulation? bonusStipulation;
  //EndGameAbility? endGameAbility;
  bool hasSigningBonus = false;
  List<Symbol> symbols = List.empty(growable: true);
  late int numberOfSymbols = 0;
  late int defendersIndex = 0;
  late int midfieldersIndex = 0;
  late int forwardsIndex = 0;
  late int benchIndex = 0;

  Position? playingPosition;
  Symbol? trySymbol;
  Symbol? chosenSymbol;

  Player(
    this.name,
    this.color,
    this.hasTheInName,
    this.points,
    this.isKeeper,
    this.isDefender,
    this.isMid,
    this.isForward,
    this.numberOfSkills,
    this.numberOfSavvies,
    this.numberOfSpeeds,
    this.numberOfStrengths,
    //this.bonusPoints,
    //this.bonusStipulation,
    //this.endGameAbility,
    this.hasSigningBonus,
  ) {
    populateSymbols();
  }

  void populateSymbols() {
    // NOTE: a symbol is added to symbols list only once, even if player has more than one of the symbol

    if (numberOfSkills >= 1) {
      symbols.add(Symbol.skill);
      ++numberOfSymbols;
    }

    if (numberOfSavvies >= 1) {
      symbols.add(Symbol.savvy);
      ++numberOfSymbols;
    }

    if (numberOfSpeeds >= 1) {
      symbols.add(Symbol.speed);
      ++numberOfSymbols;
    }

    if (numberOfStrengths >= 1) {
      symbols.add(Symbol.strength);
      ++numberOfSymbols;
    }
  }

  void setPlayingPosition(Position playingPosition) {
    this.playingPosition = playingPosition;
  }

  bool isPosition(Position position) {
    switch (position) {
      case Position.keeper:
        {
          return isKeeper;
        }
      case Position.defender:
        {
          return isDefender;
        }
      case Position.midfielder:
        {
          return isMid;
        }
      case Position.forward:
        {
          return isForward;
        }
      case Position.bench:
        {
          return true;
        }
    }
  }

  String toValuesString() {
    return '$index)';
  }

  @override
  String toString() {
    return name;
  }

  @override
  bool operator ==(Object other) {
    if (other.runtimeType != runtimeType) {
      return false;
    }
    return other is Player && other.name == name;
  }

  @override
  int get hashCode => Object.hash(index, name);
}
